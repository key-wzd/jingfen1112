async function contextFor(index, viewport={width:1440,height:1000}) {
  const context = await browser.newContext({viewport});
  await context.route('**/api/**', async route => {
    const source = new URL(route.request().url());
    if (!source.pathname.startsWith('/api/')) return route.continue();
    const response = await route.fetch({url:fixture.url+source.pathname+source.search});
    await route.fulfill({response});
  });
  const page = await context.newPage();
  page.setDefaultTimeout(12000);
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base+'/auth/login',{waitUntil:'networkidle'});
  await page.locator('#__app-loading__').waitFor({state:'hidden'});
  const account = testAccounts[index];
  await page.getByLabel('用户名',{exact:true}).fill(account.username);
  await page.getByLabel('密码',{exact:true}).fill(account.password);
  await page.getByRole('button',{name:/进入 TechCompare/}).click();
  await page.waitForURL('**/home');
  await page.goto(base+'/power/phones',{waitUntil:'networkidle'});
  await page.getByText('当前账号：'+account.username,{exact:false}).waitFor();
  await page.getByRole('button',{name:'选择筛选结果',exact:true}).waitFor();
  return {context,page};
}
async function save(page,name) {
  await page.getByLabel('分析方案名称',{exact:true}).fill(name);
  await page.getByRole('button',{name:'保存方案',exact:true}).click();
  await page.locator('.plan-success').waitFor();
}
